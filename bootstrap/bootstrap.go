// Package bootstrap implements the bootstrapping logic: generation of a .go file to
// launch the actual generator and launching the generator itself.
//
// The package may be preferred to a command-line utility if generating the serializers
// from golang code is required.
package bootstrap

import (
	"fmt"
	"go/format"
	"io/ioutil"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
)

const genPackage = "github.com/19910211/easyjson/gen"
const pkgWriter = "github.com/19910211/easyjson/jwriter"
const pkgLexer = "github.com/19910211/easyjson/jlexer"

var buildFlagsRegexp = regexp.MustCompile("'.+'|\".+\"|\\S+")
var fromPoolFunc = regexp.MustCompile(`func (\w+)FromPool\(\)`)

func unionNames(declared []string, re *regexp.Regexp, src []byte) []string {
	seen := make(map[string]struct{}, len(declared))
	out := make([]string, 0, len(declared))
	add := func(s string) {
		if _, ok := seen[s]; ok {
			return
		}
		seen[s] = struct{}{}
		out = append(out, s)
	}
	for _, s := range declared {
		add(s)
	}
	for _, m := range re.FindAllSubmatch(src, -1) {
		add(string(m[1]))
	}
	sort.Strings(out)
	return out
}

type Generator struct {
	PkgPath, PkgName         string
	Types                    []string
	PoolStructs              []string
	CloneStructs             []string
	NoStdMarshalers          bool
	SnakeCase                bool
	LowerCamelCase           bool
	OmitEmpty                bool
	OmitZero                 bool
	DisallowUnknownFields    bool
	SkipMemberNameUnescaping bool

	OutName       string
	BuildTags     string
	GenBuildFlags string

	StubsOnly   bool
	LeaveTemps  bool
	NoFormat    bool
	SimpleBytes bool
}

// writeStub outputs an initial stub for marshalers/unmarshalers so that the package
// using marshalers/unmarshales compiles correctly for boostrapping code.
func (g *Generator) writeStub(old []byte) error {
	poolTypes := unionNames(g.PoolStructs, fromPoolFunc, old)
	cloneTypes := append([]string(nil), g.CloneStructs...)
	sort.Strings(cloneTypes)
	declaredPool := make(map[string]struct{}, len(g.PoolStructs))
	for _, t := range g.PoolStructs {
		declaredPool[t] = struct{}{}
	}

	f, err := os.Create(g.OutName)
	if err != nil {
		return err
	}
	defer f.Close()

	if g.BuildTags != "" {
		fmt.Fprintln(f, "// +build ", g.BuildTags)
		fmt.Fprintln(f)
	}
	fmt.Fprintln(f, "// TEMPORARY AUTOGENERATED FILE: easyjson stub code to make the package")
	fmt.Fprintln(f, "// compilable during generation.")
	fmt.Fprintln(f)
	fmt.Fprintln(f, "package ", g.PkgName)

	if len(g.Types) > 0 {
		fmt.Fprintln(f)
		fmt.Fprintln(f, "import (")
		fmt.Fprintln(f, `  "`+pkgWriter+`"`)
		fmt.Fprintln(f, `  "`+pkgLexer+`"`)
		fmt.Fprintln(f, ")")
	}

	sort.Strings(g.Types)
	for _, t := range g.Types {
		fmt.Fprintln(f)
		if !g.NoStdMarshalers {
			fmt.Fprintln(f, "func (", t, ") MarshalJSON() ([]byte, error) { return nil, nil }")
			fmt.Fprintln(f, "func (*", t, ") UnmarshalJSON([]byte) error { return nil }")
		}

		fmt.Fprintln(f, "func (", t, ") MarshalEasyJSON(w *jwriter.Writer) {}")
		fmt.Fprintln(f, "func (*", t, ") UnmarshalEasyJSON(l *jlexer.Lexer) {}")
		fmt.Fprintln(f)
		fmt.Fprintln(f, "type EasyJSON_exporter_"+t+" *"+t)
	}

	known := make(map[string]struct{}, len(g.Types))
	for _, t := range g.Types {
		known[t] = struct{}{}
	}
	for _, t := range poolTypes {
		_, declared := declaredPool[t]
		if declared {
			if _, ok := known[t]; !ok {
				fmt.Fprintln(f)
				fmt.Fprintln(f, "type EasyJSON_exporter_"+t+" *"+t)
			}
		}
		fmt.Fprintln(f)
		fmt.Fprintln(f, "func "+t+"FromPool() *"+t+" { return new("+t+") }")
		if declared {
			fmt.Fprintln(f, "func (m *"+t+") ReturnToPool() {}")
			fmt.Fprintln(f, "func (m *"+t+") Recycle() {}")
			fmt.Fprintln(f, "func (m *"+t+") reset() {}")
		}
	}
	for _, t := range cloneTypes {
		fmt.Fprintln(f)
		fmt.Fprintln(f, "func (m *"+t+") Clone() *"+t+" { return nil }")
	}

	return nil
}

// writeMain creates a .go file that launches the generator if 'go run'.
func (g *Generator) writeMain() (path string, err error) {
	f, err := ioutil.TempFile(filepath.Dir(g.OutName), "easyjson-bootstrap")
	if err != nil {
		return "", err
	}

	fmt.Fprintln(f, "// +build ignore")
	fmt.Fprintln(f)
	fmt.Fprintln(f, "// TEMPORARY AUTOGENERATED FILE: easyjson bootstapping code to launch")
	fmt.Fprintln(f, "// the actual generator.")
	fmt.Fprintln(f)
	fmt.Fprintln(f, "package main")
	fmt.Fprintln(f)
	fmt.Fprintln(f, "import (")
	fmt.Fprintln(f, `  "fmt"`)
	fmt.Fprintln(f, `  "os"`)
	fmt.Fprintln(f)
	fmt.Fprintf(f, "  %q\n", genPackage)
	if len(g.Types) > 0 {
		fmt.Fprintln(f)
		fmt.Fprintf(f, "  pkg %q\n", g.PkgPath)
	}
	fmt.Fprintln(f, ")")
	fmt.Fprintln(f)
	fmt.Fprintln(f, "func main() {")
	fmt.Fprintf(f, "  g := gen.NewGenerator(%q)\n", filepath.Base(g.OutName))
	fmt.Fprintf(f, "  g.SetPkg(%q, %q)\n", g.PkgName, g.PkgPath)
	if g.BuildTags != "" {
		fmt.Fprintf(f, "  g.SetBuildTags(%q)\n", g.BuildTags)
	}
	if g.SnakeCase {
		fmt.Fprintln(f, "  g.UseSnakeCase()")
	}
	if g.LowerCamelCase {
		fmt.Fprintln(f, "  g.UseLowerCamelCase()")
	}
	if g.OmitEmpty {
		fmt.Fprintln(f, "  g.OmitEmpty()")
	}
	if g.OmitZero {
		fmt.Fprintln(f, "  g.OmitZero()")
	}
	if g.NoStdMarshalers {
		fmt.Fprintln(f, "  g.NoStdMarshalers()")
	}
	if g.DisallowUnknownFields {
		fmt.Fprintln(f, "  g.DisallowUnknownFields()")
	}
	if g.SimpleBytes {
		fmt.Fprintln(f, "  g.SimpleBytes()")
	}
	if g.SkipMemberNameUnescaping {
		fmt.Fprintln(f, "  g.SkipMemberNameUnescaping()")
	}

	sort.Strings(g.Types)
	for _, v := range g.Types {
		fmt.Fprintln(f, "  g.Add(pkg.EasyJSON_exporter_"+v+"(nil))")
	}

	for _, v := range g.PoolStructs {
		fmt.Fprintln(f, "  g.AddPool(pkg.EasyJSON_exporter_"+v+"(nil))")
	}

	for _, v := range g.CloneStructs {
		fmt.Fprintln(f, "  g.AddClone(pkg.EasyJSON_exporter_"+v+"(nil))")
	}

	fmt.Fprintln(f, "  if err := g.Run(os.Stdout); err != nil {")
	fmt.Fprintln(f, "    fmt.Fprintln(os.Stderr, err)")
	fmt.Fprintln(f, "    os.Exit(1)")
	fmt.Fprintln(f, "  }")
	fmt.Fprintln(f, "}")

	src := f.Name()
	if err := f.Close(); err != nil {
		return src, err
	}

	dest := src + ".go"
	return dest, os.Rename(src, dest)
}

func (g *Generator) Run() (err error) {
	old, readErr := os.ReadFile(g.OutName)
	if readErr != nil && !os.IsNotExist(readErr) {
		return readErr
	}
	defer func() {
		if err == nil {
			return
		}
		if os.IsNotExist(readErr) {
			os.Remove(g.OutName)
			return
		}
		if werr := os.WriteFile(g.OutName, old, 0644); werr != nil {
			err = fmt.Errorf("%v; restore %s: %v", err, g.OutName, werr)
		}
	}()

	if err = g.writeStub(old); err != nil {
		return err
	}
	if g.StubsOnly {
		return nil
	}

	path, err := g.writeMain()
	if err != nil {
		return err
	}
	if !g.LeaveTemps {
		defer os.Remove(path)
	}

	f, err := os.Create(g.OutName + ".tmp")
	if err != nil {
		return err
	}
	if !g.LeaveTemps {
		defer os.Remove(f.Name()) // will not remove after rename
	}

	execArgs := []string{"run"}
	if g.GenBuildFlags != "" {
		buildFlags := buildFlagsRegexp.FindAllString(g.GenBuildFlags, -1)
		execArgs = append(execArgs, buildFlags...)
	}
	if len(g.BuildTags) > 0 {
		execArgs = append(execArgs, "-tags", g.BuildTags)
	}
	execArgs = append(execArgs, filepath.Base(path))
	cmd := exec.Command("go", execArgs...)

	cmd.Stdout = f
	cmd.Stderr = os.Stderr
	cmd.Dir = filepath.Dir(path)
	err = cmd.Run()
	f.Close()
	if err != nil {
		return err
	}

	// move unformatted file to out path
	if g.NoFormat {
		return os.Rename(f.Name(), g.OutName)
	}

	// format file and write to out path
	in, err := ioutil.ReadFile(f.Name())
	if err != nil {
		return err
	}
	out, err := format.Source(in)
	if err != nil {
		return err
	}
	return ioutil.WriteFile(g.OutName, out, 0644)
}
